import {test,expect} from "@playwright/test";
for(const width of [1280,390])test("explicit one-filter recovery retains state "+width,async({page})=>{
 await page.setViewportSize({width,height:900});
 await page.goto("/shop?q=tumbler&material=Wood&sort=za&campaign=test#results");
 await page.waitForLoadState("networkidle");
 const search=page.getByRole("searchbox",{name:"Search the collection"});
 const material=page.getByRole("combobox",{name:"Material",exact:true});
 const group=page.getByRole("group",{name:"Filter recovery"});
 const action=group.getByRole("button",{name:/^All materials: [1-9]/});
 await expect(action).toBeVisible();await expect(search).toHaveValue("tumbler");await expect(material).toHaveValue("Wood");
 const count=Number((await action.innerText()).match(/: (\d+)/)![1]);
 const historyLength=await page.evaluate(()=>history.length);
 await page.reload();await expect(action).toBeVisible();await expect(material).toHaveValue("Wood");
 await action.scrollIntoViewIfNeeded();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:"D:/dot-workspace/store-filter-artifacts/recovery-"+width+".png"});
 await action.focus();await page.keyboard.press("Enter");
 await expect(search).toBeFocused();await expect(search).toHaveValue("tumbler");await expect(material).toHaveValue("All materials");
 await expect(page.locator(".catalog-grid .product-card")).toHaveCount(count);
 await expect(group).toHaveCount(0);
 expect(await page.evaluate(()=>history.length)).toBe(historyLength);
 const url=new URL(page.url());expect(url.searchParams.get("q")).toBe("tumbler");expect(url.searchParams.get("sort")).toBe("za");expect(url.searchParams.get("campaign")).toBe("test");expect(url.hash).toBe("#results");
 await page.locator(".catalog-grid .product-card h3 a").first().click();await expect(page).toHaveURL(/\/products\//);
 await page.goBack();await expect(search).toHaveValue("tumbler");await expect(material).toHaveValue("All materials");
 await page.reload();await expect(search).toHaveValue("tumbler");await expect(material).toHaveValue("All materials");
 await material.selectOption("Wood");await expect(action).toBeVisible();await action.click();await expect(search).toBeFocused();
 await material.selectOption("Wood");await search.fill("impossiblenomatch");
 await expect(page.getByRole("heading",{name:"No gifts found, just yet."})).toBeVisible();await expect(group).toHaveCount(0);
 await expect(material).toHaveValue("Wood");await expect(search).toHaveValue("impossiblenomatch");
});
