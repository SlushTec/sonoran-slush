import { test, expect } from "@playwright/test";
for (const width of [1280, 390]) {
  test("listed process discovery, navigation and typo eligibility at " + width, async ({page}) => {
    await page.setViewportSize({width,height:900});
    await page.goto("/shop?campaign=test&sort=za#results");
    await page.waitForLoadState("networkidle");
    const process = page.getByRole("combobox", {name:"Listed process",exact:true});
    const search = page.getByRole("searchbox", {name:"Search the collection"});
    await expect(process).toHaveValue("All processes");
    await expect(page.locator(".catalog-grid .product-card")).toHaveCount(41);
    const length = await page.evaluate(() => history.length);
    await process.focus();
    await page.keyboard.press("ArrowDown");
    await page.keyboard.press("Enter");
    await expect(process).toHaveValue("Laser-revealed electroplating");
    await expect(page.locator(".catalog-grid .product-card")).toHaveCount(1);
    expect(new URL(page.url()).searchParams.get("process")).toBe("Laser-revealed electroplating");
    expect(await page.evaluate(() => history.length)).toBe(length);
    await page.locator(".catalog-grid .product-card h3 a").first().click();
    await expect(page).toHaveURL(/\/products\//);
    await page.goBack();
    await expect(process).toHaveValue("Laser-revealed electroplating");
    await page.reload();
    await expect(process).toHaveValue("Laser-revealed electroplating");
    await search.fill("tumblre");
    const suggestion = page.getByRole("button", {name:"Search for tumbler",exact:true});
    await expect(suggestion).toBeVisible();
    await suggestion.click();
    await expect(search).toHaveValue("tumbler");
    await expect(process).toHaveValue("Laser-revealed electroplating");
    await expect(search).toBeFocused();
    await process.selectOption("Surface engraving on wood");
    await search.fill("tumblre");
    await expect(page.getByRole("heading", {name:"No gifts found, just yet."})).toBeVisible();
    await expect(page.getByRole("group", {name:"Search suggestions"})).toHaveCount(0);
    await page.getByRole("button", {name:"Reset filters"}).click();
    await expect(process).toHaveValue("All processes");
    await expect(search).toBeFocused();
    await expect(page.locator(".catalog-grid .product-card")).toHaveCount(41);
    expect(new URL(page.url()).searchParams.has("process")).toBe(false);
    expect(new URL(page.url()).searchParams.get("campaign")).toBe("test");
    expect(new URL(page.url()).searchParams.get("sort")).toBe("za");
    expect(new URL(page.url()).hash).toBe("#results");
    await process.selectOption("Surface engraving on wood");
    await process.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({path:"D:/dot-workspace/store-process-artifacts/process-"+width+".png"});
  });
}
